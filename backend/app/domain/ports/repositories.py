"""Repository ports. Implemented in infrastructure; faked in unit tests."""

from __future__ import annotations

from datetime import date
from typing import Protocol

from app.domain.entities import AuditEvent, Patient, StoredSourceRecord
from app.domain.fhir import FhirResourceRecord, PatientFhirState


class PatientRepository(Protocol):
    def get(self, patient_id: str) -> Patient | None: ...
    def get_by_mrn(self, mrn: str) -> Patient | None: ...
    def find_by_name_key_and_dob(self, name_key: str, dob: date) -> list[Patient]: ...
    def add(self, patient: Patient) -> None: ...
    def list_all(self) -> list[Patient]: ...


class SourceRecordRepository(Protocol):
    def get(self, record_id: str) -> StoredSourceRecord | None: ...
    def get_by_source_hash(self, source_hash: str) -> StoredSourceRecord | None: ...
    def find_original_by_content_hash(
        self, content_hash: str, exclude_record_id: str
    ) -> StoredSourceRecord | None:
        """Earliest COMPLETED or NEEDS_REVIEW record with this normalized-content hash."""
        ...
    def list_completed_for_patient(self, patient_id: str) -> list[StoredSourceRecord]:
        """COMPLETED records linked to the patient, ordered by (received_at, record_id)."""
        ...
    def add(self, record: StoredSourceRecord) -> None: ...
    def update(self, record: StoredSourceRecord) -> None: ...


class AuditLogRepository(Protocol):
    def add(self, event: AuditEvent) -> None: ...
    def list_events(self, record_id: str | None = None) -> list[AuditEvent]: ...


class FhirRepository(Protocol):
    """Generated FHIR resources (JSON) and per-patient FHIR processing state."""

    def get_state(self, patient_id: str) -> PatientFhirState | None: ...
    def save_state(self, state: PatientFhirState) -> None: ...
    def replace_resources(self, patient_id: str, resources: list[FhirResourceRecord]) -> None:
        """Atomically (within the transaction) replace ALL stored resources of the patient."""
        ...
    def list_resources(self, patient_id: str, resource_type: str | None = None) -> list[FhirResourceRecord]: ...
    def get_resource(self, resource_type: str, resource_id: str) -> FhirResourceRecord | None: ...
